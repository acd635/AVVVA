export const getProductDescription = (product: Product, lang: Language): string => {
  if (lang === 'KA') return product.descriptionKA;
  if (lang === 'EN') return product.descriptionEN;

  if (product.descriptionRU) return product.descriptionRU;

  const desc = product.descriptionKA;
  let translated = desc
    .replace(/ხელნაკეთი/gi, 'ручной работы')
    .replace(/ნატურალური/gi, 'натуральный')
    .replace(/ბუნებრივი/gi, 'натуральный')
    .replace(/ვერცხლი/gi, 'серебро')
    .replace(/მოოქროვილი/gi, 'позолоченный')
    .replace(/მარგალიტი/gi, 'жемчуг')
    .replace(/ცირკონი/gi, 'циркон')
    .replace(/ფირუზი/gi, 'бирюза')
    .replace(/ზომა/gi, 'размер')
    .replace(/სმ/gi, 'см')
    .replace(/შესაკრავით/gi, 'с замком');

  return translated || `${getProductTitle(product, 'RU')}. Эксклюзивная работа мастеров ювелирного дома AVA.`;
};
